"""
export_manager.py - Executive Decision Intelligence Export Service
Generates downloadable Executive Decision Briefs (Markdown/Text) and structured CSV packages.
"""

import pandas as pd
from datetime import datetime


def generate_executive_brief_markdown(df, anomalies_df, recommendations_df, health_score, r2_margin):
    """
    Constructs a comprehensive, professional Executive Decision Brief in Markdown format,
    suitable for C-level distribution and board pack review.
    """
    latest = df.iloc[-1]
    crit_count = len(anomalies_df[anomalies_df["severity"] == "CRITICAL"])
    high_count = len(anomalies_df[anomalies_df["severity"] == "HIGH"])
    
    timestamp_str = datetime.now().strftime("%B %d, %Y - %H:%M UTC")
    
    md = f"""# EXECUTIVE DECISION INTELLIGENCE BRIEF
**Illustrative Organization:** Microsoft Corporation (Enterprise Prototype)  
**Reporting Period:** {latest['period']} ({latest['quarter']})  
**Generated Date:** {timestamp_str}  
**Classification:** STRICTLY SYNTHETIC DEMO DATA — NOT REAL COMPANY DATA  
**Data Integrity Score:** {health_score:.1f}% Verified | **Driver Model R²:** {r2_margin:.2f}

---

## 1. EXECUTIVE SUMMARY & FINANCIAL TRAJECTORY

* **Consolidated Revenue:** **${latest['revenue_b']}B** (Target: $65.0B | Cloud Revenue: ${latest['cloud_revenue_b']}B)
* **Operating Margin:** **{latest['operating_margin_pct']}%** (Target: 45.0% | Variance: {latest['operating_margin_pct'] - 45.0:+.2f}%)
* **Operating Income:** **${latest['operating_income_b']}B** | **Free Cash Flow:** **${latest['free_cash_flow_b']}B**
* **Active Operational Alerts:** **{crit_count} Critical**, **{high_count} High** active breaches requiring management intervention.

### Key Observation:
While top-line Cloud demand remains resilient, Operating Margin is encountering compression driven by a two-stage operational transmission: elevated Tech Talent Attrition has created critical architecture vacancies, degrading Cloud SLA delivery (currently {latest['sla_delivery_pct']}%) and driving up incident MTTR. This has triggered customer renewal friction and elevated data center spot compute leasing costs.

---

## 2. CROSS-DEPARTMENTAL KPI SCORECARD

| Department | KPI Name | Current | Target | Unit | Variance | Z-Score | Severity | Accountable Owner |
| :--- | :--- | :--- | :--- | :--- | :--- | :--- | :--- | :--- |
"""
    for _, a in anomalies_df.iterrows():
        md += f"| {a['department']} | {a['kpi_name']} | {a['current_value']} | {a['target_value']} | {a['unit']} | {a['variance_pct']:+.1f}% | {a['z_score']:+.2f} | **{a['severity']}** | {a['owner']} |\n"

    md += """
---

## 3. EVIDENCE-BACKED MANAGEMENT RECOMMENDATIONS

"""
    for _, r in recommendations_df.iterrows():
        md += f"""### [{r['id']}] {r['title']}
* **Priority:** {r['priority']}  
* **Accountable Owner:** {r['owner']}  
* **Execution Timeframe:** {r['timeframe']} | **Statistical Confidence:** {r['confidence_score']}  
* **Triggering Evidence:** {r['triggering_evidence']}  
* **Expected Business Impact:** {r['expected_impact']}  
* **Underlying Assumptions:**  
  {r['assumptions']}  
* **Key Risks & Uncertainties:**  
  {r['uncertainty_and_risks']}  
* **Governance Checkpoint:** {r['governance_note']}  
* **Executive Sign-off Required:** {'[X] MANDATORY HUMAN REVIEW' if r['human_review_required'] else '[ ] Standard Operational Delegated Authority'}

"""

    md += f"""---

## 4. MODEL METHODOLOGY, LIMITATIONS & GOVERNANCE

1. **Synthetic Nature:** This brief was generated entirely using mathematical simulation scripts with a fixed random seed. No proprietary Microsoft corporate telemetry or non-public financial records were utilized.
2. **Causal Validation:** Lead-lag relationships have been evaluated using empirical Granger Causality tests (ssr F-test, p < 0.05) across {len(df)} historical monthly periods to distinguish true predictive precedence from coincident correlation.
3. **Model Limitations:** The sample size comprises {len(df)} monthly observations. In periods of macroeconomic regime shifts or unexpected regulatory interventions, operational-to-financial elasticities may exhibit non-linear deviations.
4. **Safety & Ethical Review:** Recommendations involving organizational capacity, hiring, or compensation pools require mandatory human oversight by the Chief People Officer and CFO. No automated adverse personnel actions are executed.

---
*Report generated by Executive Decision Intelligence Engine.*
"""
    return md
